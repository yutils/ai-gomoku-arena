function detectDefaultLang() {
  try {
    const nav = (typeof navigator !== 'undefined' && (navigator.language || navigator.userLanguage)) || '';
    return /^zh/i.test(nav) ? 'zh' : 'en';
  } catch {
    return 'zh';
  }
}

let lang = 'zh';
try {
  const stored = typeof localStorage !== 'undefined' ? localStorage.getItem(LS_LANG) : null;
  lang = stored === 'zh' || stored === 'en' ? stored : detectDefaultLang();
} catch {
  lang = 'zh';
}

const listeners = new Set();

export function getLang() {
  return lang;
}

// 取词，支持 {name} 占位符；缺失时回退中文，再回退 key 本身
export function t(key, params) {
  const table = DICT[lang] || DICT.zh;
  let s = table[key];
  if (s == null) s = DICT.zh[key];
  if (s == null) return key;
  if (params) {
    s = s.replace(/\{(\w+)\}/g, (m, name) => (params[name] != null ? String(params[name]) : m));
  }
  return s;
}

export function onLangChange(cb) {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

export function setLang(next) {
  if (next !== 'zh' && next !== 'en') return;
  lang = next;
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem(LS_LANG, next);
  } catch { /* 忽略 */ }
  if (typeof document !== 'undefined') document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en';
  listeners.forEach((cb) => {
    try { cb(next); } catch (e) { console.warn('i18n listener error', e); }
  });
}

export function toggleLang() {
  setLang(lang === 'zh' ? 'en' : 'zh');
}

// 静态骨架翻译：扫描 root 下带 data-i18n* 属性的元素并就地更新
export function applyStaticI18n(root = document) {
  if (!root || typeof root.querySelectorAll !== 'function') return;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.getAttribute('data-i18n')); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.getAttribute('data-i18n-title')); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.getAttribute('data-i18n-placeholder')); });
}

